export function buildCaseSummaryPrompt(params: {
  deceasedName: string;
  evidenceItems: Array<{ type: string; issuingAuthority: string; documentDate: string; certificateNumber?: string }>;
  trusteeStatements: Array<{ trusteeName: string; date: string; statement: string }>;
  timelineNotes?: string;
}): { system: string; user: string } {
  const system = `${AI_SAFETY_PREAMBLE}
TASK: Generate a concise, neutral draft case summary for human Case Reviewers (CASE_REVIEWER).
Identify key parties, checklist completeness, and any critical discrepancies (e.g. date mismatches, name spelling differences).
You MUST include the immutable non-authoritative disclaimer.

Output schema:
{
  "draftSummary": string,
  "keyParties": {
    "deceased": string,
    "trustees": string[],
    "beneficiaries": string[]
  },
  "evidenceChecklist": [
    { "item": string, "verified": boolean, "discrepancyFlag"?: string }
  ],
  "criticalDiscrepancies": string[],
  "suggestedNextSteps": string[],
  "nonAuthoritativeDisclaimer": "Draft generated by AI for triage review only. AI has zero decision authority. Human verification and independent second approval are strictly required."
}`;

  const user = `Deceased: ${params.deceasedName}
Evidence items:
${JSON.stringify(params.evidenceItems, null, 2)}
Trustee statements:
${JSON.stringify(params.trusteeStatements, null, 2)}
Timeline context:
${wrapUntrustedData(params.timelineNotes || 'None')}`;

  return { system, user };
}

export function buildEstateGuidancePrompt(question: string, readinessScore?: number): { system: string; user: string } {
  const system = `${AI_SAFETY_PREAMBLE}
TASK: Provide educational guidance to a legacy account holder.
Context: Kenya Law of Succession Act (Cap. 160), digital asset custody, trustee nomination, and progressive legacy readiness.
IMPORTANT: Do NOT give formal legal representation or financial advice. Include clear legal disclaimer.

Output schema:
{
  "answer": string,
  "suggestedActions": [
    { "title": string, "route"?: string, "reason": string }
  ],
  "successionContextKenya": string,
  "disclaimer": "This guidance is educational and does not constitute formal legal advice under Kenyan Law (Cap. 160). Consult a licensed advocate for legal will execution."
}`;

  const user = `Account readiness score: ${readinessScore ?? 0}%\nUser question:\n${wrapUntrustedData(question, 'user_question')}`;
  return { system, user };
}
